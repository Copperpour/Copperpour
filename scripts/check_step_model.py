#!/usr/bin/env python3
"""Independent kernel oracle for the fixed #543 package/assembly test case.
Development-only: pip install -r scripts/requirements-step-oracle.txt.
No Copperpour code or response fields are used to derive expected geometry.
"""
import json
import math
import sys
from OCP.STEPControl import STEPControl_Reader
from OCP.IFSelect import IFSelect_RetDone
from OCP.BRepCheck import BRepCheck_Analyzer
from OCP.Bnd import Bnd_Box
from OCP.BRepBndLib import BRepBndLib
from OCP.BRepGProp import BRepGProp
from OCP.GProp import GProp_GProps
from OCP.TopAbs import TopAbs_SOLID
from OCP.TopExp import TopExp_Explorer
from OCP.TopoDS import TopoDS
from OCP.STEPCAFControl import STEPCAFControl_Reader
from OCP.TDocStd import TDocStd_Document
from OCP.TCollection import TCollection_ExtendedString
from OCP.XCAFDoc import XCAFDoc_DocumentTool, XCAFDoc_ColorSurf, XCAFDoc_ColorGen
from OCP.TDF import TDF_LabelSequence
from OCP.Quantity import Quantity_Color, Quantity_TOC_sRGB

TOL = 1e-5

def close(actual, expected):
    assert len(actual) == len(expected)
    assert all(math.isclose(a,b,rel_tol=0,abs_tol=TOL) for a,b in zip(actual,expected)), (actual,expected)

def solids(path):
    reader = STEPControl_Reader()
    assert reader.ReadFile(str(path)) == IFSelect_RetDone, path
    assert reader.TransferRoots() > 0, path
    shape = reader.OneShape()
    assert not shape.IsNull() and BRepCheck_Analyzer(shape).IsValid(), path
    found = []
    explorer = TopExp_Explorer(shape, TopAbs_SOLID)
    while explorer.More():
        solid = TopoDS.Solid_s(explorer.Current())
        assert BRepCheck_Analyzer(solid).IsValid(), path
        box = Bnd_Box(); BRepBndLib.AddOptimal_s(solid,box,False,False)
        props = GProp_GProps(); BRepGProp.VolumeProperties_s(solid,props)
        found.append((box.Get(),props.Mass()))
        explorer.Next()
    return found

def expected(dx=0,dy=0,dz=0):
    # Body 4x6x2 mm at Z=0.3; six 0.4x0.8x0.3 mm pins, not fused.
    result = [((-2.,-3.,0.3,2.,3.,2.3),48.)]
    for y in [-3.4,3.4]:
        for x in [-1.5,0,1.5]:
            result.append(((x-0.2,y-0.4,0.,x+0.2,y+0.4,0.3),0.096))
    return [(tuple(v+offset for v,offset in zip(box,(dx,dy,dz,dx,dy,dz))),volume) for box,volume in result]

def check(actual, wanted):
    assert len(actual) == len(wanted), (len(actual),len(wanted))
    for box,volume in wanted:
        matches = [i for i,(b,v) in enumerate(actual)
                   if all(abs(x-y)<TOL for x,y in zip(box,b)) and abs(volume-v)<TOL]
        assert len(matches) == 1, (box,volume,actual)
        actual.pop(matches[0])

def colors(path):
    reader = STEPCAFControl_Reader(); reader.SetColorMode(True)
    assert reader.ReadFile(path) == IFSelect_RetDone
    doc = TDocStd_Document(TCollection_ExtendedString("test"))
    assert reader.Transfer(doc)
    st = XCAFDoc_DocumentTool.ShapeTool_s(doc.Main())
    ct = XCAFDoc_DocumentTool.ColorTool_s(doc.Main())
    found = []
    def visit(label):
        color = Quantity_Color(); shape = st.GetShape_s(label)
        if ct.GetColor(shape,XCAFDoc_ColorSurf,color) or ct.GetColor(shape,XCAFDoc_ColorGen,color):
            found.append(color.Values(Quantity_TOC_sRGB))
        subs = TDF_LabelSequence(); st.GetSubShapes_s(label,subs)
        for i in range(1,subs.Length()+1): visit(subs.Value(i))
    labels = TDF_LabelSequence(); st.GetFreeShapes(labels)
    for i in range(1,labels.Length()+1): visit(labels.Value(i))
    return found

raw = solids(sys.argv[1])
check(raw.copy(),expected())
actual_colors = colors(sys.argv[1])
assert len(actual_colors) == 7, actual_colors
for rgb in [(0.2,0.3,0.4)] + [(0.75,0.75,0.75)]*6:
    matches = [i for i,c in enumerate(actual_colors) if all(abs(a-b)<TOL for a,b in zip(c,rgb))]
    assert matches, (rgb,actual_colors)
    actual_colors.pop(matches[0])
assembly = solids(sys.argv[2])
# The substrate is not generated by this tool. Its exported thickness and
# component Z origin depend on KiCad's stack-up policy. Check the model's exact
# dimensions/volumes and relative placement under ONE common Z translation;
# raw-model validation above independently pins the requested standoff.
board = [item for item in assembly if all(abs(a-b)<TOL for a,b in zip(item[0][:2]+item[0][3:5],(0.,-20.,20.,0.))) ]
assert len(board) == 1, assembly
components = assembly.copy(); components.remove(board[0])
body = [item for item in components if abs(item[1]-48.)<TOL]
assert len(body) == 1, body
component_z = body[0][0][2] - 0.3
check(components,expected(10.,-10.,component_z))
print(json.dumps({"raw_solids":len(raw),"assembly_solids":len(assembly),
    "raw_volume_mm3":sum(v for _,v in raw),"component_z_mm":component_z,
    "kernel_valid":True,"bbox_volume_and_colors_match":True}))
